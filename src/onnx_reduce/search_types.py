"""Shared scheduling records; no search policy or model mutation."""

from __future__ import annotations

from dataclasses import dataclass

from onnx_reduce.edits import Candidate
from onnx_reduce.passes.base import ReductionPass
from onnx_reduce.types import ModelAdapter, ModelCost

PASS_SCOPE = "valid, strictly cheaper candidates generated by configured passes"
NODE_SCOPE = PASS_SCOPE + " and standard partition keep-region candidates"


@dataclass(frozen=True)
class CandidateFeedback:
    status: str
    base_cost: ModelCost
    candidate_cost: ModelCost | None = None
    cache_source: str | None = None
    failure_check_calls: int = 0
    target_identity_mismatch: bool = False
    preparation_seconds: float | None = None
    evaluation_seconds: float | None = None


@dataclass(frozen=True)
class AttemptResult:
    feedback: CandidateFeedback
    accepted_model: ModelAdapter | None = None


@dataclass(frozen=True)
class ScheduledAttempt:
    candidate: Candidate
    reduction_pass: ReductionPass
    pass_index: int
    model_version: int
    base_digest: str
    source: str = "coverage"
    direction: str = "pass"
    scale: int | None = None
    region_ids: tuple[int, ...] = ()
    stage: str | None = None
    region_source: str | None = None


@dataclass(frozen=True)
class CoverageSummary:
    base_digest: str
    model_version: int
    scope: str
    completed: bool
    inconclusive_candidate_count: int
