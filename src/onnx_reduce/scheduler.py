"""Run-local candidate scheduling, independent of editing and failure checks."""

from __future__ import annotations

from collections import Counter, OrderedDict
from collections.abc import Iterator, Sequence
from dataclasses import asdict, dataclass

from onnx_reduce.edits import Candidate, DeleteNodes
from onnx_reduce.passes.base import NodeSearchPass, ReductionPass
from onnx_reduce.passes.delete_nodes import _granularities
from onnx_reduce.performance import measure, measured, timed_candidates
from onnx_reduce.preparation import edit_key
from onnx_reduce.types import ModelAdapter, ModelCost, NodeSearchModel

PASS_SCOPE = "valid, strictly cheaper candidates generated by configured passes"
NODE_SCOPE = PASS_SCOPE + " and standard partition keep-region candidates"


@dataclass(frozen=True)
class CandidateFeedback:
    status: str
    base_cost: ModelCost
    candidate_cost: ModelCost | None = None
    cache_source: str | None = None
    failure_check_calls: int = 0
    target_identity_mismatch: bool = False
    preparation_seconds: float | None = None
    evaluation_seconds: float | None = None


@dataclass(frozen=True)
class AttemptResult:
    feedback: CandidateFeedback
    accepted_model: ModelAdapter | None = None


@dataclass(frozen=True)
class ScheduledAttempt:
    candidate: Candidate
    reduction_pass: ReductionPass
    pass_index: int
    model_version: int
    base_digest: str
    source: str = "coverage"
    direction: str = "pass"
    scale: int | None = None
    region_ids: tuple[int, ...] = ()


@dataclass(frozen=True)
class CoverageSummary:
    base_digest: str
    model_version: int
    scope: str
    completed: bool
    inconclusive_candidate_count: int


class LegacyScheduler:
    """Preserve pass order, lazy iteration and restart-on-accept exactly."""

    name = "legacy"
    scope = PASS_SCOPE

    def __init__(self, passes: Sequence[ReductionPass], model: ModelAdapter):
        self.passes = tuple(passes)
        self.model_version = 0
        self.base_digest = model.canonical_hash()
        self._pass_index = 0
        self._iterator: Iterator[Candidate] | None = None
        self._completed = False
        self._inconclusive = 0
        self._stats: dict[str, dict] = {}
        self._sources: dict[str, Counter] = {}
        self._last_visit: dict[int, int] = {}
        self.phase_revisits = 0
        self.scale_reuses = 0
        self.deduplicated = 0

    def _attempt(self, candidate, index, **metadata) -> ScheduledAttempt:
        if index in self._last_visit and self._last_visit[index] != self.model_version:
            self.phase_revisits += 1
        self._last_visit[index] = self.model_version
        return ScheduledAttempt(
            candidate,
            self.passes[index],
            index,
            self.model_version,
            self.base_digest,
            **metadata,
        )

    @measured("scheduler")
    def next_attempt(self, model: ModelAdapter) -> ScheduledAttempt | None:
        while self._pass_index < len(self.passes):
            if self._iterator is None:
                self._iterator = iter(timed_candidates(self.passes[self._pass_index], model))
            try:
                candidate = next(self._iterator)
            except StopIteration:
                self._iterator = None
                self._pass_index += 1
                continue
            return self._attempt(candidate, self._pass_index)
        self._completed = True
        return None

    def _record(self, attempt: ScheduledAttempt, feedback: CandidateFeedback) -> None:
        # Power-of-two buckets bound historical statistics even for arbitrary
        # successful scales. Exact scales remain available on each attempt.
        scale = 1 << (attempt.scale.bit_length() - 1) if attempt.scale else None
        key = f"{attempt.reduction_pass.name}/{attempt.direction}/{scale}"
        bucket = self._stats.setdefault(
            key,
            {
                "attempts": 0,
                "failure_check_calls": 0,
                "accepted": 0,
                "statuses": Counter(),
                "cache_hits": Counter(),
                "accepted_cost_delta": dict.fromkeys(asdict(feedback.base_cost), 0),
                "preparation_seconds": None,
                "evaluation_seconds": None,
            },
        )
        bucket["attempts"] += 1
        bucket["failure_check_calls"] += feedback.failure_check_calls
        bucket["statuses"][feedback.status] += 1
        if feedback.cache_source:
            bucket["cache_hits"][feedback.cache_source] += 1
        if feedback.status == "accepted":
            bucket["accepted"] += 1
            for name, before in asdict(feedback.base_cost).items():
                bucket["accepted_cost_delta"][name] += before - getattr(
                    feedback.candidate_cost, name
                )
        for name in ("preparation_seconds", "evaluation_seconds"):
            value = getattr(feedback, name)
            if value is not None:
                bucket[name] = (bucket[name] or 0.0) + value
        source = self._sources.setdefault(attempt.source, Counter())
        source["attempts"] += 1
        source["failure_check_calls"] += feedback.failure_check_calls
        source["accepted"] += feedback.status == "accepted"
        source["cache_hits"] += feedback.cache_source is not None
        for name in ("preparation_seconds", "evaluation_seconds"):
            value = getattr(feedback, name)
            if value is not None:
                source[name] += value
        if attempt.source == "coverage" and feedback.status == "inconclusive":
            self._inconclusive += 1

    def _accept(self, model: ModelAdapter) -> None:
        self.model_version += 1
        self.base_digest = model.canonical_hash()
        self._completed = False
        self._inconclusive = 0

    @measured("scheduler")
    def observe(self, attempt, feedback, accepted_model=None) -> None:
        self._record(attempt, feedback)
        if accepted_model is not None:
            self._accept(accepted_model)
            self._pass_index = 0
            self._iterator = None

    def coverage(self) -> CoverageSummary:
        return CoverageSummary(
            self.base_digest,
            self.model_version,
            self.scope,
            self._completed,
            self._inconclusive,
        )

    def to_dict(self) -> dict:
        return {
            "strategy": self.name,
            "phase_quantum": getattr(self, "phase_quantum", None),
            "model_version": self.model_version,
            "phase_revisits": self.phase_revisits,
            "scale_reuses": self.scale_reuses,
            "deduplicated": self.deduplicated,
            "coverage": asdict(self.coverage()),
            "sources": {
                name: {
                    **values,
                    "preparation_seconds": values.get("preparation_seconds"),
                    "evaluation_seconds": values.get("evaluation_seconds"),
                }
                for name, values in sorted(self._sources.items())
            },
            "buckets": {
                key: {
                    **values,
                    "statuses": dict(values["statuses"]),
                    "cache_hits": dict(values["cache_hits"]),
                    "acceptance_rate": values["accepted"] / values["attempts"],
                }
                for key, values in sorted(self._stats.items())
            },
        }


@dataclass(frozen=True)
class NodeRegion:
    ids: tuple[int, ...]

    def candidate(self, model: NodeSearchModel, direction: str, digest: str) -> Candidate | None:
        """Bind stable IDs and complements only against the current topology."""

        live = model.id_to_index
        indices = {live[node_id] for node_id in self.ids if node_id in live}
        if not indices:
            return None
        if direction == "keep":
            indices = set(range(len(model.node_ids))) - indices
        if not indices:
            return None
        return Candidate((DeleteNodes(tuple(sorted(indices))),), base_digest=digest)


class _NodeSearch:
    """Lazy partition cursor; no executable candidate survives a model change."""

    def __init__(self, reduction_pass: NodeSearchPass, model: NodeSearchModel):
        self.reduction_pass = reduction_pass
        self.size = max(1, len(model.node_ids) // 2)
        self.preferred_direction = "delete"
        self.ids: tuple[int, ...] = ()
        self.anchor: int | None = None
        self.deduplicated = 0
        self.max_seen = 4096
        self.rebase(model)

    def rebase(self, model: NodeSearchModel, attempt: ScheduledAttempt | None = None) -> None:
        if attempt is not None and attempt.scale is not None:
            self.size = attempt.scale
            self.preferred_direction = attempt.direction
        if self.ids and self.anchor in self.ids:
            start = self.ids.index(self.anchor)
            self.anchor = next(
                (
                    self.ids[(start + offset) % len(self.ids)]
                    for offset in range(len(self.ids))
                    if self.ids[(start + offset) % len(self.ids)] in model.id_to_index
                ),
                None,
            )
        self.ids = model.node_ids
        self.size = max(1, min(self.size, len(self.ids)))
        self._seen: OrderedDict[str, None] = OrderedDict()
        self._region = NodeRegion(())
        self._directions = iter(())
        self._exhausted = not self.ids
        self._start_scale(model)

    def _start_scale(self, model: NodeSearchModel) -> None:
        start = model.id_to_index.get(self.anchor, 0) // self.size
        self._regions = iter(self.reduction_pass.node_regions(model, self.size, start=start))

    def next_choice(self, model, digest):
        while not self._exhausted:
            try:
                direction = next(self._directions)
            except StopIteration:
                try:
                    self._region = NodeRegion(next(self._regions))
                except StopIteration:
                    if self.size == 1:
                        self._exhausted = True
                        return None
                    self.size = max(1, self.size // 2)
                    self.anchor = None
                    self._start_scale(model)
                    continue
                last = model.id_to_index[self._region.ids[-1]]
                self.anchor = self.ids[(last + 1) % len(self.ids)]
                other = "keep" if self.preferred_direction == "delete" else "delete"
                self._directions = iter((self.preferred_direction, other))
                continue
            candidate = self._region.candidate(model, direction, digest)
            if candidate is None:
                continue
            key = edit_key(candidate, "scheduler")
            if key in self._seen:
                self.deduplicated += 1
                continue
            if self.max_seen:
                self._seen[key] = None
                if len(self._seen) > self.max_seen:
                    self._seen.popitem(last=False)
            return candidate, direction, self.size, self._region.ids
        return None


class StatefulScheduler(LegacyScheduler):
    """Continue useful phases/scales, then verify a final deterministic sweep."""

    name = "stateful"
    phase_quantum = 8

    def __init__(self, passes: Sequence[ReductionPass], model: ModelAdapter):
        super().__init__(passes, model)
        node_passes = {
            index: reduction_pass
            for index, reduction_pass in enumerate(self.passes)
            if isinstance(reduction_pass, NodeSearchPass)
        }
        if node_passes and not isinstance(model, NodeSearchModel):
            raise ValueError("stateful node search requires node_ids and id_to_index on the model")
        self._nodes = {index: _NodeSearch(item, model) for index, item in node_passes.items()}
        if self._nodes:
            self.scope = NODE_SCOPE
        self._mode = "heuristic"
        self._phase = 0
        self._used = 0
        self._done = [False] * len(self.passes)
        self._generators = [None] * len(self.passes)
        self._coverage_iterator = None

    def _advance(self) -> None:
        self._phase = (self._phase + 1) % len(self.passes)
        self._used = 0

    def _cover(self, model):
        for index, reduction_pass in enumerate(self.passes):
            for candidate in timed_candidates(reduction_pass, model):
                metadata = {}
                if index in self._nodes and len(candidate.edits) == 1:
                    edit = candidate.edits[0]
                    if (
                        isinstance(edit, DeleteNodes)
                        and edit.indices
                        and all(0 <= i < len(model.node_ids) for i in edit.indices)
                    ):
                        metadata = {
                            "direction": "delete",
                            "scale": len(edit.indices),
                            "region_ids": tuple(model.node_ids[i] for i in edit.indices),
                        }
                yield self._attempt(candidate, index, **metadata)
        for index in self._nodes:
            reduction_pass = self.passes[index]
            for size in _granularities(len(model.node_ids)):
                for ids in reduction_pass.node_regions(model, size):
                    candidate = NodeRegion(ids).candidate(model, "keep", self.base_digest)
                    if candidate is not None:
                        yield self._attempt(
                            candidate, index, direction="keep", scale=size, region_ids=ids
                        )

    @measured("scheduler")
    def next_attempt(self, model: ModelAdapter) -> ScheduledAttempt | None:
        while self._mode == "heuristic":
            if all(self._done):
                self._mode = "coverage"
                self._coverage_iterator = iter(self._cover(model))
                break
            index = self._phase
            if self._done[index] or self._used >= self.phase_quantum:
                self._advance()
                continue
            if index in self._nodes:
                cursor = self._nodes[index]
                before = cursor.deduplicated
                with measure("candidate_generation"):
                    choice = cursor.next_choice(model, self.base_digest)
                self.deduplicated += cursor.deduplicated - before
                if choice is None:
                    self._done[index] = True
                    self._advance()
                    continue
                candidate, direction, size, ids = choice
                attempt = self._attempt(
                    candidate,
                    index,
                    source="heuristic",
                    direction=direction,
                    scale=size,
                    region_ids=ids,
                )
            else:
                if self._generators[index] is None:
                    self._generators[index] = iter(timed_candidates(self.passes[index], model))
                try:
                    candidate = next(self._generators[index])
                except StopIteration:
                    self._done[index] = True
                    self._advance()
                    continue
                attempt = self._attempt(candidate, index, source="heuristic")
            self._used += 1
            return attempt
        try:
            return next(self._coverage_iterator)
        except StopIteration:
            self._completed = True
            return None

    @measured("scheduler")
    def observe(self, attempt, feedback, accepted_model=None) -> None:
        self._record(attempt, feedback)
        if accepted_model is None:
            return
        self._accept(accepted_model)
        for index, cursor in self._nodes.items():
            hint = attempt if attempt.pass_index == index and attempt.scale is not None else None
            cursor.rebase(accepted_model, hint)
            if hint is not None and accepted_model.node_ids:
                self.scale_reuses += 1
        self._generators = [None] * len(self.passes)
        self._done = [False] * len(self.passes)
        self._coverage_iterator = None
        if self._mode == "coverage":
            self._phase = attempt.pass_index
            self._used = 1
        self._mode = "heuristic"
